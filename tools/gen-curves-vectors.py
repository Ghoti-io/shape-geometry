"""Print the exact model of the lowering of a conic arc to cubics (stroke_curves.h, SG40).

An independent statement, in 60-digit decimal arithmetic and none of the library's
code, of what the lowering does to a circular arc of radius `r` whose middle
weight is `w` (an exact double; the ends have weight 1): the handle fraction
`4 w / (3 (1 + w))` of the control legs, the weight `sqrt((1 + w) / 2)` of a half
after an exact bisection of the conic, the radial error of the cubic, computed
from the cubic's own control points (not from the closed form the library uses:
the maximum over the parameter of `|Q(t)| - r`, found by a fine scan and refined by
golden-section search), and the number of halvings the rule "the least k with
r e(w_k) <= tolerance" takes.

Run it with the standard library only:

    python3 tools/gen-curves-vectors.py > tests/curves_vectors.h

Every number is written as a hexadecimal floating literal of the nearest double.
"""
import math
import sys
from decimal import Decimal, getcontext

getcontext().prec = 60

ANGLES_DEG = [179.0, 150.0, 120.0, 90.0, 60.0, 45.0, 30.0, 22.5, 15.0, 5.0]


def hexf(x):
    return float(x).hex()


def sqrt(x):
    return Decimal(x).sqrt()


def cubic_for(w, r):
    """Control points of the cubic for the arc with middle weight w (exact double) and radius r, centre at the origin,
    the arc symmetric about +x: ends (r c, -+ r s), c = w, s = sqrt(1 - w^2)."""
    w = Decimal(w)
    r = Decimal(r)
    s = sqrt(1 - w * w)
    p0 = (r * w, -r * s)
    p2 = (r * w, r * s)
    p1 = (r / w, Decimal(0))
    lam = 4 * w / (3 * (1 + w))
    q1 = (p0[0] + lam * (p1[0] - p0[0]), p0[1] + lam * (p1[1] - p0[1]))
    q2 = (p2[0] + lam * (p1[0] - p2[0]), p2[1] + lam * (p1[1] - p2[1]))
    return p0, q1, q2, p2, lam


def bez(c, t):
    t = Decimal(t)
    u = 1 - t
    x = u ** 3 * c[0][0] + 3 * u * u * t * c[1][0] + 3 * u * t * t * c[2][0] + t ** 3 * c[3][0]
    y = u ** 3 * c[0][1] + 3 * u * u * t * c[1][1] + 3 * u * t * t * c[2][1] + t ** 3 * c[3][1]
    return x, y


def max_radial_error(w, r):
    """max over t of |Q(t)| - r, relative to r, from the control points."""
    p0, q1, q2, p2, _ = cubic_for(w, r)
    c = (p0, q1, q2, p2)

    def f(t):
        x, y = bez(c, t)
        return sqrt(x * x + y * y) / Decimal(r) - 1

    best = Decimal(0)
    n = 400
    arg = 0
    for i in range(n + 1):
        v = f(Decimal(i) / n)
        if v > best:
            best, arg = v, i
    lo = Decimal(max(arg - 1, 0)) / n
    hi = Decimal(min(arg + 1, n)) / n
    g = (sqrt(5) - 1) / 2
    for _ in range(120):
        a = hi - g * (hi - lo)
        b = lo + g * (hi - lo)
        if f(a) < f(b):
            lo = a
        else:
            hi = b
    return max(best, f((lo + hi) / 2))


def half_weight(w):
    return float(sqrt((1 + Decimal(w)) / 2))


def halvings(w, r, tol):
    k = 0
    while max_radial_error(w, r) * Decimal(r) > Decimal(tol):
        w = half_weight(w)
        k += 1
        if k > 30:
            raise SystemExit("no convergence")
    return k


def main():
    out = []
    out.append("/* Generated by tools/gen-curves-vectors.py; do not edit. */\n")
    out.append("/* SPDX-License-Identifier: LGPL-3.0-only */\n")
    out.append("#ifndef GHOTI_IO_GSHGEOM_TESTS_CURVES_VECTORS_H\n#define GHOTI_IO_GSHGEOM_TESTS_CURVES_VECTORS_H\n\n")
    out.append("#include <cstddef>\n\nnamespace curves_vectors {\n\n")
    out.append("/** One circular arc, radius 1, middle weight w: the model's cubic for it. */\n")
    out.append("struct Arc {\n  double angle_deg, w, lambda, w_half;\n  double q1x, q1y;  ///< the first inner control point\n"
               "  double error;     ///< max radial error of the cubic, relative to the radius\n};\n\n")
    out.append("static const Arc arcs[] = {\n")
    for a in ANGLES_DEG:
        w = math.cos(math.radians(a) / 2)
        p0, q1, q2, p2, lam = cubic_for(w, 1.0)
        e = max_radial_error(w, 1.0)
        out.append("    {%s, %s, %s, %s, %s, %s, %s},\n" % (hexf(a), hexf(w), hexf(lam), hexf(half_weight(w)),
                                                          hexf(q1[0]), hexf(q1[1]), hexf(e)))
    out.append("};\nstatic const size_t arc_count = sizeof arcs / sizeof arcs[0];\n\n")
    out.append("/** The halvings the rule takes: the least k with r e(w_k) <= tolerance. */\n")
    out.append("struct Halvings {\n  double w, radius, tolerance;\n  int k;\n};\n\n")
    out.append("static const Halvings halvings_table[] = {\n")
    for a in [90.0, 120.0, 60.0, 179.0]:
        w = math.cos(math.radians(a) / 2)
        for r in [1.0, 100.0, 5000.0]:
            for tol in [2.0 ** -12, 2.0 ** -14, 0.25]:
                out.append("    {%s, %s, %s, %d},\n" % (hexf(w), hexf(r), hexf(tol), halvings(w, r, tol)))
    out.append("};\nstatic const size_t halvings_count = sizeof halvings_table / sizeof halvings_table[0];\n\n")
    out.append("} // namespace curves_vectors\n\n#endif /* GHOTI_IO_GSHGEOM_TESTS_CURVES_VECTORS_H */\n")
    sys.stdout.write("".join(out))


if __name__ == "__main__":
    main()
